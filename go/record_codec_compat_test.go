// Keep the public method-bearing carriers until their named breaking window.
// Integer widths and the timestamp wrapper require conversion, not aliases.
func TestGeneratedRecordFieldParity(t *testing.T) {
	for _, pair := range [][2]reflect.Type{{reflect.TypeOf(Record{}), reflect.TypeOf(wire.Record{})}, {reflect.TypeOf(Attestation{}), reflect.TypeOf(wire.Attestation{})}} {
		if pair[0].NumField() != pair[1].NumField() {
			t.Fatalf("field count: %v versus %v", pair[0], pair[1])
		}
		for i := 0; i < pair[0].NumField(); i++ {
			old, generated := pair[0].Field(i), pair[1].Field(i)
			name := strings.Split(old.Tag.Get("json"), ",")[0]
			if !strings.EqualFold(name, generated.Name) {
				t.Fatalf("field %s is not %s", name, generated.Name)
			}
			if old.Type == reflect.TypeOf(Timestamp{}) {
				if generated.Type.Kind() != reflect.String {
					t.Fatal("timestamp carrier drift")
				}
			} else if old.Type.Kind() == reflect.Int {
				if generated.Type.Kind() != reflect.Int64 {
					t.Fatal("integer carrier drift")
				}
			} else if old.Type.Kind() != generated.Type.Kind() {
				t.Fatalf("field %s type drift: %v versus %v", name, old.Type, generated.Type)
			} else if old.Type.Kind() == reflect.Map && (old.Type.Key() != generated.Type.Key() || old.Type.Elem() != generated.Type.Elem()) {
				t.Fatalf("field %s map carrier drift", name)
			} else if old.Type.Kind() == reflect.Slice && (old.Type.Elem() != reflect.TypeOf(Attestation{}) || generated.Type.Elem() != reflect.TypeOf(wire.Attestation{})) {
				t.Fatalf("field %s list carrier drift", name)
			}
		}
	}
}

func TestGeneratedCodecRetainedCorpusValuesAndProvenance(t *testing.T) {
	files, err := filepath.Glob("../testdata/records/*.jsonl")
	if err != nil || len(files) == 0 {
		t.Fatalf("retained corpus: %v %v", files, err)
	}
	for _, path := range files {
		data, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		for _, line := range bytes.Split(bytes.TrimSpace(data), []byte("\n")) {
			old, err := DecodeRecord(line)
			if err != nil {
				t.Fatalf("%s legacy: %v", path, err)
			}
			generated, err := wire.Decode(line)
			if err != nil {
				t.Fatalf("%s generated: %v", path, err)
			}
			var converted Record
			if err := json.Unmarshal(wire.Encode(generated), &converted); err != nil {
				t.Fatal(err)
			}
			if !reflect.DeepEqual(old, converted) {
				t.Fatalf("%s value drift", path)
			}
			originalBytes, err := old.Encode()
			if err != nil || !bytes.Equal(originalBytes, append(append([]byte(nil), line...), '\n')) {
				t.Fatalf("%s retained body bytes changed: %v", path, err)
			}
			key := []byte("retained corpus fixture key")
			old.Identity = append(Identity(nil), old.Identity...)
			converted.Identity = append(Identity(nil), converted.Identity...)
			hop := len(old.Identity) - 1
			if hop < 0 {
				t.Fatal("corpus has no provenance")
			}
			if err := old.Bind(hop, "fixture", key); err != nil {
				t.Fatal(err)
			}
			if err := converted.Bind(hop, "fixture", key); err != nil {
				t.Fatal(err)
			}
			policy := Policy{Keys: map[string][]byte{"fixture": key}}
			if !reflect.DeepEqual(old, converted) || !reflect.DeepEqual(old.Assess(nil, policy), converted.Assess(nil, policy)) {
				t.Fatalf("%s provenance drift", path)
			}
			oldBytes, err := old.Encode()
			if err != nil {
				t.Fatal(err)
			}
			parsed, err := wire.Decode(oldBytes)
			if err != nil {
				t.Fatal(err)
			}
			if bytes.Equal(oldBytes, wire.Encode(parsed)) {
				t.Fatal("expected unresolved compact-versus-generated byte boundary")
			}
			t.Logf("%s: values/Assess/Bind match; persisted Encode bytes differ", filepath.Base(path))
		}
	}
}

// These are held compatibility counterexamples, rather than permission to
// tighten the existing storage reader or change persisted body bytes.
func TestGeneratedCodecMigrationCompatibilityBoundaries(t *testing.T) {
	base := `{"schema":1,"time":"2026-09-15T01:49:58.123456Z","level":0,"msg":"ok"}`
	cases := map[string][]byte{
		"missing required fields":        []byte(`{"schema":1}`),
		"case insensitive known field":   []byte(strings.Replace(base, `"msg"`, `"MSG"`, 1)),
		"null message":                   []byte(strings.Replace(base, `"ok"`, `null`, 1)),
		"null optional list":             []byte(strings.TrimSuffix(base, "}") + `,"identity":null}`),
		"null map string value":          []byte(strings.TrimSuffix(base, "}") + `,"attrs":{"key":null}}`),
		"missing nested required fields": []byte(strings.TrimSuffix(base, "}") + `,"identity":[{}]}`),
		"invalid UTF-8 replacement":      bytes.Replace([]byte(base), []byte("ok"), []byte{0xff}, 1),
		"lone surrogate replacement":     []byte(strings.Replace(base, `"ok"`, `"\ud800"`, 1)),
		"depth beyond generated bound":   []byte(strings.TrimSuffix(base, "}") + `,"future":` + strings.Repeat("[", 70) + `0` + strings.Repeat("]", 70) + `}`),
	}
	for name, line := range cases {
		t.Run(name, func(t *testing.T) {
			_, legacyErr := DecodeRecord(line)
			_, generatedErr := wire.Decode(line)
			if legacyErr != nil || generatedErr == nil {
				t.Fatalf("boundary changed: legacy=%v generated=%v", legacyErr, generatedErr)
			}
			t.Logf("legacy accepts; generated refuses: %v", generatedErr)
		})
	}
}

func TestGeneratedCodecEscapingAlsoChangesRetainedBytes(t *testing.T) {
	line := []byte(`{"schema":1,"time":"2026-09-15T01:49:58.123456Z","level":0,"msg":"<>&\u2028"}`)
	old, err := DecodeRecord(line)
	if err != nil {
		t.Fatal(err)
	}
	legacyBytes, err := old.Encode()
	if err != nil {
		t.Fatal(err)
	}
	generated, err := wire.Decode(line)
	if err != nil {
		t.Fatal(err)
	}
	var compact bytes.Buffer
	if err := json.Compact(&compact, wire.Encode(generated)); err != nil {
		t.Fatal(err)
	}
	if bytes.Equal(bytes.TrimSpace(legacyBytes), compact.Bytes()) {
		t.Fatal("expected unresolved JSON string-escaping byte boundary")
	}
}
